/**
 * v0.34.0: bundle the mobile/iPad web viewer (webclient/index.html) into a
 * JS module the main process can serve, WITHOUT reading a source-tree file
 * at runtime (which would break in the packaged asar — see CLAUDE.md §21).
 *
 * It emits main/webclientHtml.js = `module.exports = "<html as a JSON
 * string>";`. The electron build then compiles that into
 * dist-electron/main/webclientHtml.js, and the server does
 * `require('../webclientHtml')` to serve the page at GET /m.
 *
 * Run automatically in `predist` (so release builds always carry the
 * latest viewer), and any time you edit webclient/index.html:
 *   node scripts/build-webclient.js
 */
const fs = require('node:fs');
const path = require('node:path');

const SRC = path.join(__dirname, '..', 'webclient', 'index.html');
const OUT = path.join(__dirname, '..', 'main', 'webclientHtml.js');

const html = fs.readFileSync(SRC, 'utf8');
const banner =
  '// AUTO-GENERATED by scripts/build-webclient.js from webclient/index.html.\n' +
  '// Do NOT edit by hand — edit webclient/index.html and re-run the script\n' +
  '// (or just `npm run dist`, which regenerates this in predist).\n';
fs.writeFileSync(OUT, banner + 'module.exports = ' + JSON.stringify(html) + ';\n');

console.log(`[build-webclient] wrote ${path.relative(path.join(__dirname, '..'), OUT)} (${html.length} bytes of HTML)`);
